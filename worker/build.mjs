/* Builds the connector into one file, worker/dist/worker.mjs: js/snapshot.js
   (shared with the page), then worker/src/mcp.js, then the export. One file
   with no imports deploys the same way everywhere: `wrangler deploy`, or
   pasted into the Cloudflare dashboard's editor.

     node worker/build.mjs           write it
     node worker/build.mjs --check   fail if it is out of date */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const read = path => readFileSync(new URL(path, root), "utf8").trimEnd();
export const OUTPUT = fileURLToPath(new URL("worker/dist/worker.mjs", root));

export function buildWorker(){
  return [
    "// Generated by worker/build.mjs from js/snapshot.js and worker/src/mcp.js.",
    "// Edit those files and rebuild; changes made here are overwritten.",
    "",
    read("js/snapshot.js"),
    "",
    read("worker/src/mcp.js"),
    "",
    "export default createWorker();",
    ""
  ].join("\n");
}

if(process.argv[1] === fileURLToPath(import.meta.url)){
  const built = buildWorker();
  if(process.argv.includes("--check")){
    let current = "";
    try{ current = readFileSync(OUTPUT, "utf8"); }catch(e){}
    if(current !== built){
      console.error("worker/dist/worker.mjs is out of date. Run: npm run build");
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, built);
    console.log(`Wrote ${OUTPUT} (${built.length} bytes)`);
  }
}
